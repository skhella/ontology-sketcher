import type { Namespace } from './model'
import { namespacePrefixes } from './namespaces'

/**
 * Neo4j export: a Cypher script that loads the exported Turtle into Neo4j as a labeled property graph
 * through neosemantics (n10s). The script is run by the user in Neo4j Browser or cypher-shell; nothing
 * here connects to a database or asks for credentials.
 */

export interface CypherScriptInput {
  /** The ontology IRI from the toolbar; its namespace gets a readable prefix in Neo4j. */
  iri: string
  /** The OWL ontology in Turtle, as toTurtle() writes it. */
  ontology: string
  /** The SHACL shapes in Turtle, or null when no class has constraints. */
  shapes: string | null
  /** The project's other namespaces; each keeps its own prefix in Neo4j. */
  namespaces?: Namespace[]
}

/** A Cypher string literal holding `text` unchanged: backslashes and single quotes are escaped. */
export function cypherString(text: string): string {
  return "'" + text.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'"
}

/** A short prefix for the ontology namespace: http://example.org/pizza# → pizza. Falls back to "onto". */
export function prefixFor(iri: string): string {
  const last = iri.replace(/[#/]+$/, '').split(/[/#:]/).pop() ?? ''
  const prefix = last.toLowerCase().replace(/[^a-z0-9_]/g, '')
  return /^[a-z]/.test(prefix) ? prefix.slice(0, 20) : 'onto'
}

/** The namespace classes and properties live in: the ontology IRI, ending in # or / like owl.ts expects. */
function namespaceOf(iri: string): string {
  return /[#/]$/.test(iri) ? iri : iri + '#'
}

/** Builds the .cypher script: n10s setup, then the ontology import, then the shapes import when there are shapes. */
export function toCypherScript({ iri, ontology, shapes, namespaces }: CypherScriptInput): string {
  const prefix = prefixFor(iri)
  const others = Object.entries(namespacePrefixes(namespaces, namespaceOf(iri))).filter(([p]) => p !== prefix)
  const lines = [
    '// Generated by Ontology Sketcher: loads the ontology into Neo4j as a labeled property graph.',
    '// Needs the neosemantics (n10s) plugin: https://neo4j.com/labs/neosemantics/',
    '// Run it on an empty database in Neo4j Browser (paste and run) or with',
    '//   cypher-shell -u neo4j -d neo4j -f ontology.cypher',
    '// To run it again, first clear the database:',
    '//   MATCH (n) DETACH DELETE n;  CALL n10s.graphconfig.drop();',
    '',
    '// 1. n10s keeps every resource unique by its IRI.',
    'CREATE CONSTRAINT n10s_unique_uri IF NOT EXISTS FOR (r:Resource) REQUIRE r.uri IS UNIQUE;',
    '',
    '// 2. Graph config.',
    "//   handleVocabUris 'SHORTEN' turns IRIs into prefix__localName labels and property keys",
    '//   (rdfs:label becomes rdfs__label), so the graph stays readable and can be exported back to RDF.',
    "//   Use 'IGNORE' instead for bare local names, at the cost of losing namespaces.",
    "//   handleMultival 'ARRAY' keeps every label and comment, e.g. one per language.",
    'CALL n10s.graphconfig.init({',
    "  handleVocabUris: 'SHORTEN',",
    "  handleMultival: 'ARRAY',",
    '  keepLangTag: true',
    '});',
    '',
    `// 3. A readable prefix for the ontology's namespace${others.length ? ' and the other namespaces' : ''} instead of n10s's generated ns0.`,
    `CALL n10s.nsprefixes.add(${cypherString(prefix)}, ${cypherString(namespaceOf(iri))});`,
    ...others.map(([p, ns]) => `CALL n10s.nsprefixes.add(${cypherString(p)}, ${cypherString(ns)});`),
    '',
    '// 4. The ontology. n10s.onto.import keeps named classes (:Class), object properties (:Relationship),',
    '//   data properties (:Property), rdfs:subClassOf (SCO), rdfs:subPropertyOf (SPO),',
    '//   rdfs:domain (DOMAIN), rdfs:range (RANGE), and rdfs:label and rdfs:comment.',
    '//   It leaves out restrictions, equivalent and disjoint classes, property characteristics,',
    '//   inverses, union domains and ranges, and other annotations: the .ttl export keeps all of those.',
    `CALL n10s.onto.import.inline(${cypherString(ontology)}, 'Turtle');`,
  ]
  if (shapes) {
    lines.push(
      '',
      '// 5. The SHACL shapes, stored by n10s for validating instance data you load later,',
      "//   e.g. with n10s.rdf.import.fetch(...). Check that data with: CALL n10s.validation.shacl.validate();",
      `CALL n10s.validation.shacl.import.inline(${cypherString(shapes)}, 'Turtle');`,
    )
  }
  return lines.join('\n') + '\n'
}
